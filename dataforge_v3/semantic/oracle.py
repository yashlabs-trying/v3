"""Reference-oracle interface and probe aggregation (V3.2, supports B and D).

An oracle is an *independent* executable judge of a task's observable behavior.
It is written from the task's declared contract, not from the benchmark's hidden
tests and not from the gold patch. Probes are generated by the Semantic Test
Generator (module B) or supplied as mutations/alternatives (module C); the
oracle runs them and reports outcomes.

Two oracle families are provided in `dataforge_v3/semantic/tasks/`:
  * in-process Python oracles (openlibrary): import the candidate module.
  * containerized Go oracles (flipt): inject generated tests into the task image.
Both expose the same `run_probes()` surface so module D is task-agnostic.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Protocol, runtime_checkable

from dataforge_v3.semantic.model import ClauseEvidence, ProbeOutcome, ProbeResult


@dataclass
class ProbeCase:
    """One executable probe launched against a candidate submission."""

    name: str
    kind: str
    clauses: list[str] = field(default_factory=list)
    payload: dict[str, Any] = field(default_factory=dict)


@runtime_checkable
class ReferenceOracle(Protocol):
    """Independent executable model of a task's contract."""

    task: str

    def run(self, cases: list[ProbeCase]) -> list[ProbeResult]:
        ...


def to_evidence(results: list[ProbeResult]) -> list[ClauseEvidence]:
    """Convert probe results into per-clause evidence entries."""
    evidence: list[ClauseEvidence] = []
    for r in results:
        outcome = ProbeOutcome.PASS if r.passed else ProbeOutcome.FAIL
        for clause_id in r.clauses:
            evidence.append(
                ClauseEvidence(
                    clause_id=clause_id,
                    probe=r.name,
                    outcome=outcome,
                    counterexample=r.counterexample,
                    observed=r.observed,
                    expected=r.expected,
                    detail=r.detail,
                )
            )
    return evidence


def summarize_probes(results: list[ProbeResult]) -> dict[str, Any]:
    passed = sum(1 for r in results if r.passed)
    return {
        "probes": len(results),
        "passed": passed,
        "failed": len(results) - passed,
        "by_kind": _count_by(results, "kind"),
    }


def _count_by(results: list[ProbeResult], attr: str) -> dict[str, int]:
    out: dict[str, int] = {}
    for r in results:
        key = getattr(r, attr)
        out[key] = out.get(key, 0) + 1
    return out

GO_ORACLE = r'''
// Code generated by DataForge V3.2 semantic oracle. DO NOT EDIT.
// Independent properties derived from the contract; no gold expectation.
package models

import (
	"testing"
)

// dfScoreOrderP passes iff the confidence slice is non-increasing in Score.
func dfScoreOrderP(cs Confidences) bool {
	for i := 1; i < len(cs); i++ {
		if cs[i-1].Score < cs[i].Score {
			return false
		}
	}
	return true
}

// dfStringList renders confidences as "score / method".
func dfStringList(cs Confidences) []string {
	out := make([]string, 0, len(cs))
	for _, c := range cs {
		out = append(out, c.String())
	}
	return out
}

func dfIndexOf(cs Confidences, method DetectionMethod) int {
	for i, c := range cs {
		if c.DetectionMethod == method {
			return i
		}
	}
	return -1
}

func TestDataForgeVulsOrdering(t *testing.T) {
	t.Run("score.order", func(t *testing.T) {
		scoreCases := []Confidences{
			{OvalMatch, CpeVendorProductMatch},
			{CpeVendorProductMatch, OvalMatch},
			{ChangelogLenientMatch, ChangelogExactMatch, CpeVendorProductMatch},
			{CpeVendorProductMatch, ChangelogLenientMatch, ChangelogExactMatch},
		}
		for i, in := range scoreCases {
			got := in.SortByConfident()
			if !dfScoreOrderP(got) {
				t.Errorf("score.order[%d]: not non-increasing: %v", i, dfStringList(got))
			}
		}
	})

	t.Run("tie.order", func(t *testing.T) {
		// For equal scores (CpeVersionMatch=100, OvalMatch=100) the pre-existing
		// behavior yields OvalMatch first.
		tieCases := []Confidences{
			{CpeVersionMatch, OvalMatch},
			{OvalMatch, CpeVersionMatch},
		}
		for i, in := range tieCases {
			got := in.SortByConfident()
			oi := dfIndexOf(got, OvalMatch.DetectionMethod)
			ci := dfIndexOf(got, CpeVersionMatch.DetectionMethod)
			if oi < 0 || ci < 0 {
				t.Errorf("tie.order[%d]: missing method in %v", i, dfStringList(got))
				continue
			}
			if oi > ci {
				t.Errorf("tie.order[%d]: expected OvalMatch before CpeVersionMatch, got %v", i, dfStringList(got))
			}
		}
		// JVN product vs Oval (10 vs 100) must order by score.
		jvn := Confidences{CpeVendorProductMatch, OvalMatch}.SortByConfident()
		if jvn[0].DetectionMethod != OvalMatch.DetectionMethod {
			t.Errorf("tie.order[jvn]: expected high score first, got %v", dfStringList(jvn))
		}
	})
}
'''


def generate_go_oracle() -> str:
    return GO_ORACLE


Executor = Callable[[dict], ProbeResult]


_PREFIX_CLAUSE = {
    "score.order": "sort.by_score",
    "tie.order": "sort.equal_score_order",
}


def clauses_for_probe(name: str) -> list[str]:
    for prefix, clause in _PREFIX_CLAUSE.items():
        if name.startswith(prefix):
            return [clause]
    return []


@dataclass
class VulsOracle:
    task: str = TASK
    executor: Executor | None = None

    def run(self, cases, candidates=None) -> list[ProbeResult]:  # type: ignore[override]
        if self.executor is None:
            return [
                ProbeResult(
                    name="vuls:no-executor",
                    kind="differential",
                    passed=False,
                    detail="no executor configured",
                )
            ]
        probe_src = generate_go_oracle()
        results: list[ProbeResult] = []
        for name, source in candidates or []:
            if hasattr(source, "read_text"):
                src = source.read_text(encoding="utf-8")
            else:
                src = Path(source).read_text(encoding="utf-8")
            results.append(
                self.executor(
                    {"candidate": name, "vulninfos_source": src, "oracle_source": probe_src}
                )
            )
        return results

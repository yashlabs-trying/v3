"""Independent contract + oracle for the vuls confidence-ordering task (V3.2).

Focus (per Phase 2 expansion): the disputed `SortByConfident` behaviour.

  * CONTRACT            - clauses from the instruction plus *established
                          behaviour* evidenced by the pre-existing test. Each
                          clause records whether it is instruction-derived or
                          compatibility-derived, so the adjudication can say
                          which kind of requirement a failure violates.
  * generate_go_oracle  - a self-contained Go test run against the candidate's
                          `models` package. It asserts two independent
                          properties:
                            (P1) score order  - result is non-increasing in Score
                            (P2) tie order    - equal-score items follow the order
                                                established by pre-existing tests
                          and reports them as separate subtests.
  * VulsOracle          - runner abstraction over an injected Docker executor.

The oracle does NOT hardcode the DeepSeek tie order or any gold expectation. The
tie order asserted in P2 comes from the *pre-existing* test, which is part of the
task's retained test surface (the official test patch keeps it).
"""

